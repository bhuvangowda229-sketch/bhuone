function Clean-Module($code) {
    # Remove lines starting with import
    $code = [System.Text.RegularExpressions.Regex]::Replace($code, '(?m)^\s*import\s+.*?;\r?\n?', '')
    # Replace export class with class
    $code = [System.Text.RegularExpressions.Regex]::Replace($code, '(?m)^\s*export\s+class\s+', 'class ')
    # Replace export default with empty
    $code = [System.Text.RegularExpressions.Regex]::Replace($code, '(?m)^\s*export\s+default\s+', '')
    # Replace any remaining export { ... }
    $code = [System.Text.RegularExpressions.Regex]::Replace($code, '(?m)^\s*export\s+\{.*?\};?\r?\n?', '')
    return $code
}

